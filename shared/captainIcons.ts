type Group = (typeof CAPTAIN_ICON_GROUPS)[number]
export type CaptainIconId = Group["icons"][number][0]
export type CaptainIconGroup = Group["name"]

export interface CaptainIconInfo {
  id: CaptainIconId
  label: string
  group: CaptainIconGroup
  /** Lower-case words search matches: the label's, the id's, the group's and the extra ones. */
  words: string
}

/** "ship-wheel" → "Ship wheel". */
const spoken = (id: string) => (id.charAt(0).toUpperCase() + id.slice(1)).replace(/-/g, " ")

let all: readonly CaptainIconInfo[] | null = null
let byId: ReadonlyMap<string, CaptainIconInfo> | null = null

/** Every icon in the picker, in its order: the groups one after another. */
export function captainIcons(): readonly CaptainIconInfo[] {
  all ??= CAPTAIN_ICON_GROUPS.flatMap((g) =>
    g.icons.map((icon): CaptainIconInfo => {
      const [id, more, label = spoken(id)] = icon as readonly [CaptainIconId, string, string?]
      return { id, label, group: g.name, words: `${label} ${id.replace(/-/g, " ")} ${g.name} ${more}`.toLowerCase() }
    }),
  )
  return all
}

export function captainIconInfo(id: string | null | undefined): CaptainIconInfo | undefined {
  byId ??= new Map(captainIcons().map((i) => [i.id, i]))
  return id ? byId.get(id) : undefined
}

/** One of the catalogue's ids: the only values a Captain icon may be saved as. */
export const isCaptainIcon = (v: unknown): v is CaptainIconId => typeof v === "string" && captainIconInfo(v) !== undefined

/** The picker's search: icons with every word of `query` at the start of one of theirs ("sh wh" finds Ship wheel). */
export function searchCaptainIcons(query: string): readonly CaptainIconInfo[] {
  const terms = query.toLowerCase().split(/[^a-z0-9']+/).filter(Boolean)
  if (!terms.length) return captainIcons()
  return captainIcons().filter((i) => {
    const words = i.words.split(/[^a-z0-9']+/)
    return terms.every((t) => words.some((w) => w.startsWith(t)))
  })
}
